const { chromium } = require(process.env.DESHA_PLAYWRIGHT_PATH || 'playwright');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
 await page.evaluate(()=>document.fonts.ready);
 fs.mkdirSync('.sites-runtime/qa',{recursive:true});
 await page.screenshot({path:'.sites-runtime/qa/desktop.png',fullPage:true});
 const badImages=await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src));
 if(badImages.length)throw new Error('Broken images: '+badImages.join(','));
 await page.getByRole('button',{name:'තාක්ෂණය',exact:true}).click();
 if(await page.locator('.news-card').count()!==1)throw new Error('Category filter failed');
 await page.getByRole('button',{name:'මුල් පිටුව',exact:true}).click();
 await page.getByRole('textbox',{name:'පුවත් සොයන්න'}).fill('කොළඹ');
 if(await page.locator('.news-card').count()!==1)throw new Error('Search failed');
 await page.getByRole('textbox',{name:'පුවත් සොයන්න'}).fill('zzzz-no-results');
 await page.getByRole('heading',{name:'පුවත් හමු වුණේ නැහැ'}).waitFor();
 await page.getByRole('textbox',{name:'පුවත් සොයන්න'}).fill('');
 const save=page.getByRole('button',{name:'ලිපිය සුරකින්න'}).first();await save.click();
 if(!await page.evaluate(()=>JSON.parse(localStorage.getItem('desha-saved')).length))throw new Error('Bookmark failed');
 await page.reload({waitUntil:'networkidle'});
 if(!await page.getByRole('button',{name:'සුරැකීම ඉවත් කරන්න'}).count())throw new Error('Bookmark persistence failed');
 await page.getByRole('button',{name:'තවත් පුවත් බලන්න'}).click();
 if(await page.locator('.latest-item').count()!==8)throw new Error('Load more failed');
 await page.locator('.hero-story').click();
 await page.locator('.article-copy').waitFor();
 await page.screenshot({path:'.sites-runtime/qa/article.png',fullPage:true});
 await page.goto('http://localhost:3000/?category='+encodeURIComponent('ක්‍රීඩා'),{waitUntil:'networkidle'});
 if(await page.locator('.news-card').count()!==1)throw new Error('Deep linked category failed');
 await page.setViewportSize({width:390,height:844});
 await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
 await page.screenshot({path:'.sites-runtime/qa/mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Mobile horizontal overflow');
 await page.getByRole('button',{name:'මෙනුව විවෘත කරන්න'}).click();
 await page.getByRole('textbox',{name:'පුවත් සොයන්න'}).fill('කොළඹ');
 if(await page.locator('.news-card').count()!==1)throw new Error('Mobile search failed');
 if(errors.length)throw new Error(errors.join('\n'));
 console.log('PASS: images, category filtering, search, empty state, saved articles, persistence, load more, article routes, category URLs, mobile navigation, mobile search, no overflow, no JavaScript errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
